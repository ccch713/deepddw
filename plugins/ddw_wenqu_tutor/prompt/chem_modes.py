# ===== 模式注册表 =====

CHEM_MODES: dict[str, ChemModeCard] = {
    m.key: m for m in [
        MODE_SUBSTANCE_CHANGE, MODE_ION_REDOX,
        MODE_QUANT_CALC, MODE_EXPERIMENT,
        MODE_TEST_IDENTIFY, MODE_PURIFY_SEPARATE,
        MODE_CHART_TABLE, MODE_PROCESS_FLOW,
        MODE_ELECTROCHEM, MODE_STRUCTURE, MODE_ORGANIC,
    ]
}

MODE_KEYS: list[str] = list(CHEM_MODES.keys())


def identify_mode(
    question_text: str,
    knowledge_points: str = "",
) -> str | None:
    """基于关键词确定性匹配识别题目模式。

    优先匹配 knowledge_points（更精准），再匹配 question_text。
    返回匹配命中的第一个模式 key，无匹配返回 None。
    """
    text_combined = f"{knowledge_points} {question_text}"
    # 按关键词出现次数计分，取最高分
    scores: dict[str, int] = {}
    for key, card in CHEM_MODES.items():
        count = sum(
            1 for kw in card.keywords
            if kw in text_combined
        )
        if count > 0:
            scores[key] = count

    if not scores:
        return None
    return max(scores, key=scores.get)


def build_mode_card_prompt(mode_key: str) -> str:
    """为指定模式生成 prompt 卡片文本。"""
    card = CHEM_MODES.get(mode_key)
    if not card:
        return ""

    steps = "\n".join(card.process_steps)
    pitfalls = "\n".join(f"- {p}" for p in card.pitfalls)

    return f"""\
【当前题目模式】{card.name}（{card.key}）

【处理顺序】
{steps}

【易错点提醒】
{pitfalls}"""


